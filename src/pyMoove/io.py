def load_positions_parquet(filePath: str | Path)->pd.DataFrame:
    """Load processed position data from parquet file into panda Dataframe
    filePath: Path to file str or Path"""
    dataset = pd.read_parquet(filePath)

    # Consistent type format for ID's
    dataset["IDs"] = dataset["IDs"].astype("string")
    dataset["NIDs"] = dataset["NIDs"].astype("string")

    # Consistent time-format to utc
    dataset["datetime"] = dataset["datetime"].dt.tz_convert("UTC")

    return dataset

def load_bin_stats_parquet(filePath: str | pd.DataFrame)->pd.DataFrame:
    """Load pre-computed feed-bin position statistics parquet."""
    return pd.read_parquet(filePath)


def load_replacements_parquet(filePath: str | Path)->pd.DataFrame:
    """Load processed replacements data from parquet file into panda Dataframe
    filePath: Path to file str or Path"""

    dataset = pd.read_parquet(filePath)

    # Consistent type format for ID's
    dataset["actor_cow"] = dataset["actor_cow"].astype("string")
    dataset["reactor_cow"] = dataset["reactor_cow"].astype("string")

    # Consistent time-format to utc
    dataset["time"] = dataset["time"].dt.tz_convert("UTC")

    # Assign ID's to replacement events:
    if "repl_id" not in dataset.columns:
        dataset = moovePreprocess.assign_replacement_id(dataset)

    mooveValidate.check_replacement_ids(dataset)

    return dataset


def load_feeding_parquet(filePath: str | Path)->pd.DataFrame:
    """Load feeding parquet"""

    dataset = pd.read_parquet(filePath)

    #NOTE: Perhaps more convenient to have this already performed from the scritps..
    # Extract date from filename, e.g. Feed_251010.parquet
    date = pd.to_datetime(
        Path(filePath).stem.split("_")[-1],
        format="%y%m%d"
    ).strftime("%Y-%m-%d")

    # Combine date with feeding start time and convert to UTC
    dataset["start_time"] = (
        pd.to_datetime(date + " " + dataset["start_time"].astype(str))
        .dt.tz_localize("Europe/Stockholm")
        .dt.tz_convert("UTC")
    )

    # Calculate end time using visit duration (handles midnight crossing)
    dataset["end_time"] = (
        dataset["start_time"]
        + pd.to_timedelta(dataset["duration"], unit="s")
    )
    return dataset


def load_processed_dataset(dataFolderPath: str | Path)->datasetFull:
    """
    Load preprocessed positioning, feeding and replacement data.

    Loads the parquet files generated by AniSpace and moo4feed preprocessing scripts.

    Params:
    ---------
    dataFolderPath: str or Path
        Directory where the data is located

    Returns
    ---------
    dict[str, pd.DataFrame]
        Python dictionary containing three datasets:
            - "positions": AniSpace cleaned and interpolated RTLS position data
            - "feeding": Feeding visits records
            - "replacements": moo4feed Detected replacement events
    """

    folder = Path(dataFolderPath)

    #NOTE: Hardcoded for now
    #TODO: eventually fix hardcoding of filePaths
    dataset = {
        "positions": load_positions_parquet(folder/"rtls_cleaned_anispace.parquet"),
        "feeding": load_feeding_parquet(
            folder / "Feed_251010.parquet"
        ),
        "replacements": load_replacements_parquet(
            folder / "feed_replacements_20251010.parquet"
        ),
    }

    #TODO: Displaying memory is a useful metric, can all loading functions have this,
    # can we generalize it and make the functionality public or something?
    print(f"\nLoaded dataset in folder: {folder}")
    tot_mb = 0;
    for name, df in dataset.items():
        mem_mb = df.memory_usage(deep=True).sum() / 1024**2
        tot_mb += mem_mb

        print(
            f"  {name} "
                f"Memory: {mem_mb:.2f} MiB"
        )
    print(f"Total memory: {tot_mb:.2f} MiB\n")

    return dataset


